"""异步入门：通过主智能体的更新流理解事件循环。

同步调用：例如 invoke()，调用者要等它返回，才能执行下一行。
异步执行：遇到可异步等待的操作时，协程可以暂停，让事件循环运行其他就绪任务。
网络请求适合这种方式；异步不会直接让模型生成或网络传输变快。

执行路线：导入模块 → 创建协程对象 → 启动事件循环 → 执行协程
→ 逐次等待并打印更新 → 流结束 → 协程结束 → 清理并关闭事件循环。

本例只提交了一个主任务。async 不等于自动开启线程，也不等于自动并行；
安排多个独立协程并发执行时，可以再学习 asyncio.create_task() 和 gather()。
"""

# asyncio 是 Python 标准库，提供事件循环、任务调度等功能，不需要单独安装。
import asyncio

# 导入构造好的智能体。导入时仍会执行目标模块的顶层代码，
# 这部分初始化不会因为后面写了 async 而自动变成异步。
from agent.main_agent import run_deep_agent


if __name__ == "__main__":
    # 此入口仅在直接运行本文件时执行，其他文件 import 本模块时不会执行。
    # 先调用 run_main_agent() 得到协程对象，再由 asyncio.run() 创建事件循环并执行。
    # 事件循环负责调度协程，并在等待操作就绪后让协程继续。
    # asyncio.run() 会等主协程结束才返回，最后清理并关闭它创建的事件循环。
    # 在已经运行事件循环的 async 函数内，通常直接 await 协程，而不是再次 asyncio.run()。
    asyncio.run(run_deep_agent("请调用市场情报助手，搜索近一个月中国智能眼镜市场的公开消息，总结三条趋势并附来源链接。", "demo_001"))
